"""War Thunder's controls from exported controls files (.blk): every hotkey (ID_*, <axis>_rangeMax
...) and axis named in the files given, written as catalog/<version>.gob. The game keeps its full
list inside its packed data, so the list grows with the files it is given.

usage: python -I catalog.py <version> <controls.blk>...
"""
import re
import sys
from pathlib import Path

WORDS = {
    "MGUNS": "machine guns", "MGUN": "machine gun", "AAM": "air-to-air missiles",
    "AGM": "air-to-ground missiles", "ATGM": "ATGM", "FBW": "fly-by-wire", "FPS": "first person",
    "TPS": "third person", "FPV": "FPV", "MFD": "MFD", "IRCM": "IRCM", "UAV": "UAV", "UGV": "UGV",
    "IFF": "IFF", "ACM": "ACM", "HUD": "HUD", "PTT": "push to talk", "AI": "AI", "AA": "AA",
    "MISSLE": "missile", "HOMMING": "homing", "WO": "without", "CAMX": "camera X",
    "CAMY": "camera Y", "CAM": "camera", "POS": "position", "PRIM": "primary", "SEC": "secondary",
    "IR": "IR", "GUI": "GUI", "VTOL": "VTOL", "FWD": "forward", "VERT": "vertical",
    "X": "X", "Y": "Y", "Z": "Z", "MPSTATSCREEN": "multiplayer statistics",
    "FLIGHTMENU": "flight menu", "SCHRAEGE": "Schräge", "MUSIK": "Musik",
}
# Words that only say which vehicle: the category tells it.
VEHICLE = {"HELICOPTER", "HELI", "SHIP", "SUBMARINE", "HUMAN", "GM", "TANK", "SUIT"}
RANGE = {"rangeMax": "increase", "rangeMin": "decrease", "rangeSet": "set"}


def category(raw):
    w = set(re.split(r"_", raw.upper()))
    if w & {"HELICOPTER", "HELI"}:
        return "Helicopter"
    if "SUBMARINE" in w:
        return "Submarine"
    if "SHIP" in w:
        return "Naval"
    if w & {"HUMAN", "SUIT"}:
        return "Infantry"
    if w & {"GM", "TANK", "ARTILLERY", "SUSPENSION", "TRACKS", "UGV", "TERRAFORM"}:
        return "Ground"
    if "REPLAY" in w:
        return "Replay"
    if w & {"SENSOR", "RADAR", "MFD"}:
        return "Sensors"
    if w & {"CAMERA", "CAMX", "CAMY", "CAM", "VIEW", "ZOOM", "HEAD", "TRACKER", "BINOCULARS"}:
        return "Camera"
    if w & {"VOICE", "PTT", "SCREENSHOT", "HUD", "HELP", "FLIGHTMENU", "PAUSE", "CONTINUE",
            "MAP", "MPSTATSCREEN", "CURSOR", "LOG", "MENU", "SETUP"}:
        return "General"
    return "Aircraft"


def name(raw):
    words = [t for t in raw.upper().split("_") if t and t not in VEHICLE]
    out = [WORDS.get(t, t.lower()) for t in words] or [raw.lower()]
    text = " ".join(out)
    return text[0].upper() + text[1:]


def main():
    version, paths = sys.argv[1], sys.argv[2:]
    hotkeys, axes = set(), set()
    for p in paths:
        section = None
        for line in Path(p).read_text(encoding="utf-8", errors="replace").splitlines():
            if re.match(r"^  (hotkeys|axes)\{", line):
                section = line.strip()[:-1]
            elif re.match(r"^  \S", line):
                section = None
            elif section and (m := re.match(r"^    ([A-Za-z0-9_]+)\{", line)):
                (hotkeys if section == "hotkeys" else axes).add(m.group(1))
    hotkeys -= {"AUTOBIND_TEST_SHORTCUT", "UNUSED"}
    actions = []
    for axis in axes:
        actions.append((category(axis), name(axis), axis, "axis"))
    for hk in hotkeys:
        m = re.match(r"^(.+)_(rangeMax|rangeMin|rangeSet)$", hk)
        if m:
            actions.append((category(m.group(1)), f"{name(m.group(1))}: {RANGE[m.group(2)]}", hk, None))
        elif hk.startswith("ID_"):
            actions.append((category(hk[3:]), name(hk[3:]), hk, None))
    actions.sort()
    out = [f"# War Thunder {version}: the controls named in exported controls files.",
           "# Generated by dev/catalog.py; do not edit by hand.", ""]
    for cat, label, aid, kind in actions:
        out += ["[[action]]", f'id = "{aid}"', f'category = "{cat}"', f'name = "{label}"']
        if kind:
            out.append(f'kind = "{kind}"')
        out.append("")
    dest = Path(__file__).resolve().parent.parent / "catalog" / f"{version}.gob"
    dest.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(dest, len(actions))


main()
