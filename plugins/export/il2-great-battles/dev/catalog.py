"""Builds catalog/<version>.gob of the IL-2 Great Battles export plugin from key mapping files.

    python -I dev/catalog.py <game version> <global.actions> [more .actions files ...]

The game writes every action it knows into data/input/global.actions, one line per input:
"action, input, invert| // the game's English text". The file has no groups; the tabs of the
game's Key mapping menu follow the file's order, so each group starts at a known action.
More files only add evidence of which actions are axes (an axis input or an "a/b" pair).
Run by the maintainer on request; not shipped.
"""

import json
import sys
from datetime import date
from pathlib import Path

PLUGIN = Path(__file__).resolve().parent.parent

# The first action of each tab of the game's Key mapping menu, in the file's order.
GROUPS = [
    ("screenshot", "Service"),
    ("cam_reset", "Camera controls"),
    ("freelook", "Pilot head control"),
    ("autopilot", "Plane controls"),
    ("autoaltitudinalcorrection", "Plane engine controls"),
    ("all_guns_fire", "Weapons controls"),
    ("bc_signal_stay_here", "Flight leader orders"),
    ("vc_gas", "Tank controls"),
    ("ext_action1", "Other"),
]
# The mouse in the game's own menus: nothing to bind.
SKIP = ("gui_mouse_",)


def lines(path: Path):
    for line in path.read_text("utf-8", errors="replace").splitlines():
        if line.startswith("//") or line.startswith("&") or not line.strip():
            continue
        body, _, comment = line.partition("//")
        parts = [p.strip() for p in body.split(",")]
        if len(parts) >= 2 and parts[0]:
            yield parts[0], parts[1], comment.strip()


def pretty(action: str) -> str:
    return action.replace("_", " ").capitalize()


def build(paths):
    order, text, axes = [], {}, set()
    for n, path in enumerate(paths):
        for action, command, comment in lines(path):
            if n == 0 and action not in order:
                order.append(action)
            # A text the game left as its string-table key ("inprb_pitch") is no name.
            if comment and not comment.startswith("inp"):
                text.setdefault(action, comment)
            if "/" in command or "_axis_" in command or action.startswith("rpc_"):
                axes.add(action)
    group = "Other"
    starts = dict(GROUPS)
    for action in order:
        group = starts.get(action, group)
        if action.startswith(SKIP):
            continue
        name = text.get(action, pretty(action))
        yield {"id": action, "category": group, "name": name, "kind": "axis" if action in axes else "button"}
        if action in axes:
            # An axis also takes two buttons, written "first/second" on one line.
            yield {"id": action + ":inc", "category": group, "name": name + " (+)", "kind": "button"}
            yield {"id": action + ":dec", "category": group, "name": name + " (−)", "kind": "button"}


def main():
    version, paths = sys.argv[1], [Path(p) for p in sys.argv[2:]]
    out = [
        f"# IL-2 Sturmovik: Great Battles {version}: actions of the game's key mapping file.",
        f"# Generated by dev/catalog.py on {date.today().isoformat()}; do not edit by hand.",
    ]
    count = 0
    for a in build(paths):
        count += 1
        out += ["", "[[action]]"]
        out += [f"{k} = {json.dumps(a[k], ensure_ascii=False)}" for k in ("id", "category", "name")]
        if a["kind"] != "button":
            out.append(f'kind = "{a["kind"]}"')
    target = PLUGIN / "catalog" / f"{version}.gob"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out) + "\n", "utf-8")
    print(f"{target.name}: {count} actions")


if __name__ == "__main__":
    main()
