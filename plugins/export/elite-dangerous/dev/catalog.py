"""Builds catalog/<major>.<minor>.gob of the Elite Dangerous plugin.

    python dev/catalog.py <file.binds> <actions.json> > catalog/4.2.gob

<file.binds>: a bindings file the game wrote (Options/Bindings/Custom.4.2.binds), which lists every
element the game knows, or the empty preset; its root's MajorVersion/MinorVersion name the catalog.
<actions.json>: names, groups and kinds of the elements, as the public-domain
elite-dangerous-bindings project keeps them (public/data/actions.json). Only elements of the
bindings file with a name there are listed, in the game's menu order.
"""

import json
import re
import sys
from datetime import date

GROUPS = {
    "OnFoot": "On foot",
    "UI": "Interface",
    "Misc": "Miscellaneous",
}


def category(group, section):
    group = GROUPS.get(group, group)
    norm = lambda s: re.sub(r"[^a-z]", "", s.lower())
    if norm(section) in (norm(group), "misc", "miscellaneous", "onfoot", "multicrew", "srv"):
        return group
    return f"{group}: {section}"


def toml(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(binds_path, actions_path):
    text = open(binds_path, encoding="utf-8-sig").read()
    version = re.search(r'MajorVersion="(\d+)" MinorVersion="(\d+)"', text)
    version = f"{version.group(1)}.{version.group(2)}" if version else "?"
    # Elements with bindings: a <Binding> (axis) or <Primary> (button) right inside them.
    kinds = {}
    for tag, inner in re.findall(r"^\t<([A-Za-z0-9_]+)>\s*\n\t\t<(Binding|Primary)\b", text, re.M):
        kinds.setdefault(tag, "axis" if inner == "Binding" else "button")
    actions = json.load(open(actions_path, encoding="utf-8"))
    actions = [a for a in actions if a["code"] in kinds]
    actions.sort(key=lambda a: a.get("order", 0))
    out = [
        f"# Elite Dangerous {version}: the elements of the game's bindings files that take an input.",
        f"# Generated by dev/catalog.py on {date.today().isoformat()}; do not edit by hand.",
    ]
    seen = set()
    for a in actions:
        if a["code"] in seen:
            continue
        seen.add(a["code"])
        out += [
            "",
            "[[action]]",
            f"id = {toml(a['code'])}",
            f"category = {toml(category(a['group'], a['section']))}",
            f"name = {toml(a['name'])}",
        ]
        if kinds[a["code"]] == "axis":
            out.append('kind = "axis"')
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    print("\n".join(out))
    print(f"{len(seen)} actions", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:3])
