"""Builds catalog/<version>.gob of the Microsoft Flight Simulator export plugin from control profiles.

    python -I dev/catalog.py <2020|2024> <profile.xml> [more profiles ...] [--names <en-US.locPak>]

A profile of the 2024 sim lists every action it knows, bound or not, in contexts
(<Context ContextName="SURFACES">); its general profile has the contexts for every aircraft, a
category profile (<AircraftInfo CategoryName="AIRPLANE"/>) those of one kind of aircraft. Give it
a general profile and one of each category. Action ids: "CONTEXT/ACTION" for general actions,
"CATEGORY:CONTEXT/ACTION" for those of a category. The 2020 sim has no categories and writes only
bound actions, so its catalog is made from the same 2024 profiles without categories (its own
profiles add their actions): actions new in 2024 may show up there too.
The sim's names come from its en-US.locPak (JSON, key "INPUT.<action>"); without it the names
are made from the action ids. Run by the maintainer on request; not shipped.
"""

import json
import re
import sys
from datetime import date
from pathlib import Path

PLUGIN = Path(__file__).resolve().parent.parent

# Developer tools of the sim: nothing to bind for flying.
SKIP_CONTEXTS = {"DEBUG", "DEVMODE", "DEVMODECAMERA"}
# Contexts the 2020 sim does not have.
NOT_2020 = re.compile(
    r"^(PLAYER_CHARACTER_.*|EFB.*|WORLDMAP_.*|MISSION_FLOW_TOOLS|TRUE_COCKPIT|.*_ACTIVE_INTERACTION|"
    r"TOUCHSCREEN_INTERACTIONS|RTC|AIRCRAFT_PC)$"
)
CATEGORY_NAMES = {"AIRPLANE": "Airplanes", "HELICOPTER": "Helicopters"}
# Words kept in capitals in names made from ids.
UPPER = {"ATC", "AP", "ADF", "VOR", "NAV", "COM", "GPS", "ILS", "DME", "HSI", "OBS", "EFB", "VR",
         "PFD", "MFD", "FMS", "FD", "IAS", "VS", "ALT", "HDG", "APU", "ECAM", "XPNDR", "UI", "TCAS",
         "ELT", "FLC", "LOC", "GS", "CDI", "RPM", "EGT", "TOGA", "EX1", "ADI", "HUD"}


def profile(path: Path):
    """(category, [(context, [(action, flag)])]) of one profile file."""
    text = path.read_text("utf-8", errors="replace")
    category = ""
    m = re.search(r'<AircraftInfo\s+CategoryName="([^"]*)"', text)
    if m:
        category = m.group(1)
    contexts, current = [], None
    for m in re.finditer(r'<Context\s+ContextName="([^"]*)"|<Action\s+ActionName="([^"]*)"([^>]*)>', text):
        if m.group(1) is not None:
            current = (m.group(1), [])
            contexts.append(current)
        elif current is not None:
            flag = re.search(r'Flag="(\d+)"', m.group(3) or "")
            current[1].append((m.group(2), int(flag.group(1)) if flag else 0))
    return category, contexts


def pretty(name: str) -> str:
    words = name.removeprefix("KEY_").removesuffix("_EX1").split("_")
    axis = "AXIS" in words
    if axis:
        # "AXIS_ELEVATOR_SET" -> "Elevator (axis)"
        words = [w for w in words if w not in ("AXIS", "SET")] or ["AXIS"]
    out = []
    for i, w in enumerate(words):
        if w.upper() in UPPER:
            out.append(w.upper())
        elif i == 0:
            out.append(w.capitalize())
        else:
            out.append(w.lower())
    return " ".join(out) + (" (axis)" if axis else "")


def is_axis(action: str, flag: int) -> bool:
    return flag & 4 != 0 or "AXIS" in action or action.endswith(("_SET", "_SET_EX1"))


def build(version, paths, names):
    seen, out, axes = set(), [], set()
    for path in paths:
        category, contexts = profile(path)
        if version == "2020":
            category = ""
        for context, actions in contexts:
            if context in SKIP_CONTEXTS or (version == "2020" and NOT_2020.match(context)):
                continue
            group = pretty(context)
            if category:
                group = f"{CATEGORY_NAMES.get(category, category.capitalize())}: {group}"
            for action, flag in actions:
                id = f"{category}:{context}/{action}" if category else f"{context}/{action}"
                if is_axis(action, flag):
                    axes.add(id)
                if id in seen:
                    continue
                seen.add(id)
                name = names.get(f"INPUT.{action}") or pretty(action)
                out.append({"id": id, "category": group, "name": name})
    for a in out:
        a["kind"] = "axis" if a["id"] in axes else "button"
    return out


def main():
    args = sys.argv[1:]
    names = {}
    if "--names" in args:
        i = args.index("--names")
        pak = json.loads(Path(args[i + 1]).read_text("utf-8-sig"))
        names = pak.get("LocalisationPackage", {}).get("Strings", {})
        del args[i : i + 2]
    version, paths = args[0], [Path(p) for p in args[1:]]
    out = [
        f"# Microsoft Flight Simulator {version}: actions of the sim's control profiles.",
        f"# Generated by dev/catalog.py on {date.today().isoformat()}; do not edit by hand.",
    ]
    actions = build(version, paths, names)
    for a in actions:
        out += ["", "[[action]]"]
        out += [f"{k} = {json.dumps(a[k], ensure_ascii=False)}" for k in ("id", "category", "name")]
        if a["kind"] != "button":
            out.append(f'kind = "{a["kind"]}"')
    target = PLUGIN / "catalog" / f"{version}.gob"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out) + "\n", "utf-8")
    print(f"{target.name}: {len(actions)} actions")


if __name__ == "__main__":
    main()
