"""Builds catalog/<game version>.gob of the X4: Foundations plugin.

    python dev/catalog.py <inputmap.xml> <contexts.xml> > catalog/9.00.gob

Both files are the game's own `libraries/inputmap.xml` (the default bindings, which list every
control that can be bound) and `libraries/contexts.xml` (where each control works), unpacked from
the game's .cat/.dat archives with Egosoft's X Catalog Tool. Names come from the controls' ids;
categories from the first context a control is in. Debug, VR and cheat controls are left out.
"""

import re
import sys
from datetime import date

# Contexts in the order they name a category: a control in several takes the first.
CONTEXTS = [
    ("INPUT_CONTEXT_FLIGHT", "Flight"),
    ("INPUT_CONTEXT_MOUSESTEERING", "Flight"),
    ("INPUT_CONTEXT_SHIP", "Ship"),
    ("INPUT_CONTEXT_TARGET", "Targets"),
    ("INPUT_CONTEXT_TARGETMOUSE", "Targets"),
    ("INPUT_CONTEXT_CAMERA", "Camera"),
    ("INPUT_CONTEXT_CAMERA_COCKPIT", "Camera"),
    ("INPUT_CONTEXT_CAMERA_EXTERNAL", "Camera"),
    ("INPUT_CONTEXT_SPACE", "Flight"),
    ("INPUT_CONTEXT_PLAYER", "Player"),
    ("INPUT_CONTEXT_FIRST_PERSON", "On foot"),
    ("INPUT_CONTEXT_FIRST_PERSON_INTERACTION", "On foot"),
    ("INPUT_CONTEXT_MAP", "Map"),
    ("INPUT_CONTEXT_MAP_FOCUS", "Map"),
    ("INPUT_CONTEXT_MAP_FOCUS_ROTATE_ITEM", "Map"),
    ("INPUT_CONTEXT_COMPASSMENU", "Radial menus"),
    ("INPUT_CONTEXT_INFO_ACTION", "Interactions"),
    ("INPUT_CONTEXT_COMM_ACTION", "Interactions"),
    ("INPUT_CONTEXT_SCAN_ACTION", "Interactions"),
    ("INPUT_CONTEXT_TELEPORT_ACTION", "Interactions"),
    ("INPUT_CONTEXT_UNDOCK_ACTION", "Interactions"),
    ("INPUT_CONTEXT_GET_UP_ACTION", "Interactions"),
    ("INPUT_CONTEXT_INTERACTIVE_NOTIFICATION", "Interactions"),
    ("INPUT_CONTEXT_CONVERSATION", "Conversations"),
    ("INPUT_CONTEXT_CONVERSATION_MANAGER", "Conversations"),
    ("INPUT_CONTEXT_MENUS", "Menus"),
    ("INPUT_CONTEXT_WIDGET_FRAME", "Menus"),
    ("INPUT_CONTEXT_DIALOG_MENU", "Menus"),
    ("INPUT_CONTEXT_DIALOG_MENU_GAMEPAD", "Menus"),
    ("INPUT_CONTEXT_ADDON_CHATWINDOW", "Menus"),
    ("INPUT_CONTEXT_BASE", "General"),
    ("INPUT_CONTEXT_TOGGLED_HUD", "General"),
]
# Controls whose context is in other files (the map's, the cinematic camera's): by their id.
BY_ID = [
    ("DETAILMONITOR", "Map"),
    ("CINEMATIC", "Camera"),
    ("_FP_", "On foot"),
    ("WIDGET", "Menus"),
    ("DIALOG", "Menus"),
    ("HELPTEXT", "Menus"),
    ("CONTROLLERMOUSE", "Menus"),
    ("SKIP_", "General"),
    ("START_GAME", "General"),
    ("CUTSCENE", "General"),
]
SKIP = re.compile(r"DEBUG|_VR_|^INPUT_[A-Z]+_VR|CHEAT")
PREFIXES = {"INPUT_ACTION_": "button", "INPUT_STATE_": "button", "INPUT_RANGE_": "axis"}
# Words of ids written out.
WORDS = {
    "FP": "on foot",
    "ADDON": "",
    "DETAILMONITOR": "map",
    "SETA": "SETA",
    "HUD": "HUD",
    "FPS": "FPS",
    "UI": "UI",
}


def name(control_id):
    for prefix in PREFIXES:
        if control_id.startswith(prefix):
            control_id = control_id[len(prefix):]
    words = []
    for w in control_id.split("_"):
        w = WORDS.get(w, w.lower())
        if w:
            words.append(w)
    text = " ".join(words)
    return text[:1].upper() + text[1:]


def toml(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(inputmap_path, contexts_path, version="9.00"):
    inputmap = open(inputmap_path, encoding="utf-8-sig").read()
    contexts = open(contexts_path, encoding="utf-8-sig").read()
    where = {}
    for ctx, body in re.findall(r'<context id="([A-Z_0-9]+)">(.*?)</context>', contexts, re.S):
        for control in re.findall(r'<(?:action|state|range) id="([A-Z_0-9]+)"', body):
            where.setdefault(control, []).append(ctx)
    order = [c for c, _ in CONTEXTS]
    titles = dict(CONTEXTS)
    out = [
        f"# X4: Foundations {version}: the controls of the game's default bindings (libraries/inputmap.xml).",
        f"# Generated by dev/catalog.py on {date.today().isoformat()}; do not edit by hand.",
    ]
    seen = set()
    for control in re.findall(r'<(?:action|state|range) id="([A-Z_0-9]+)"', inputmap):
        if control in seen or SKIP.search(control):
            continue
        kind = next((k for p, k in PREFIXES.items() if control.startswith(p)), None)
        if kind is None:
            continue
        ctxs = where.get(control, [])
        if any("DEBUG" in c for c in ctxs) and not any(c in titles for c in ctxs):
            continue
        seen.add(control)
        known = sorted((c for c in ctxs if c in titles), key=order.index)
        by_id = next((t for part, t in BY_ID if part in control), None)
        category = titles[known[0]] if known else (by_id or "Other")
        out += ["", "[[action]]", f"id = {toml(control)}", f"category = {toml(category)}", f"name = {toml(name(control))}"]
        if kind == "axis":
            out.append('kind = "axis"')
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    print("\n".join(out))
    print(f"{len(seen)} controls", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:4])
